// ===== Navbar Scroll =====
function initNavbar() {
  const navbar = document.getElementById('navbar');
  window.addEventListener('scroll', () => {
    navbar.classList.toggle('scrolled', window.scrollY > 50);
  }, { passive: true });
}

// ===== Language Toggle =====
function initLanguageToggle() {
  const btn = document.getElementById('lang-toggle');
  btn.addEventListener('click', () => {
    currentLang = currentLang === 'zh' ? 'en' : 'zh';
    applyLanguage();
  });
}

function applyLanguage() {
  const dict = I18N[currentLang];
  
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    // In WeChat browser, prefer Wechat-specific keys if available
    const wcKey = isWeChatBrowser ? key + 'Wechat' : null;
    const text = (wcKey && dict[wcKey]) || dict[key];
    if (text) el.textContent = text;
  });

  document.getElementById('lang-en').className = currentLang === 'en' ? 'active' : '';
  document.getElementById('lang-zh').className = currentLang === 'zh' ? 'active' : '';
  document.documentElement.lang = currentLang === 'zh' ? 'zh-CN' : 'en';

  renderLUTGrid();
  renderFAQ();
}

// ===== Floating QR =====
function initFloatingQR() {
  const floatingQR = document.getElementById('floating-qr');
  const modal = document.getElementById('qr-modal');

  // Show/hide on scroll
  window.addEventListener('scroll', () => {
    const show = window.scrollY > 300 && !modal.classList.contains('open');
    floatingQR.classList.toggle('visible', show);
  }, { passive: true });

  // Click to open modal
  floatingQR.addEventListener('click', () => {
    modal.classList.add('open');
    floatingQR.classList.remove('visible');
  });
}

// ===== QR Modal =====
function initQRModal() {
  const modal = document.getElementById('qr-modal');
  const openBtns = [document.getElementById('btn-scan'), document.getElementById('btn-scan-bottom')];
  const closeBtn = document.getElementById('btn-close-qr');

  openBtns.forEach(btn => {
    if (btn) btn.addEventListener('click', () => modal.classList.add('open'));
  });

  closeBtn.addEventListener('click', () => modal.classList.remove('open'));
  modal.addEventListener('click', (e) => {
    if (e.target === modal) modal.classList.remove('open');
  });

  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') modal.classList.remove('open');
  });
}

// ===== Feature Tabs =====
function initFeatureTabs() {
  document.querySelectorAll('.feature-tab').forEach(tab => {
    tab.addEventListener('click', () => {
      const category = tab.getAttribute('data-category');
      if (category === currentCategory) return;
      currentCategory = category;
      document.querySelectorAll('.feature-tab').forEach(t => t.classList.remove('active'));
      tab.classList.add('active');
      renderLUTGrid();
    });
  });
}

